"""Stage the SupplyLens API for Vercel (service `api`, root deploy/vercel-api) and keep its dependency pins honest.

Committed in deploy/vercel-api: index.py (entrypoint), pyproject.toml (dependencies pinned to uv.lock), .python-version
and hosted_storage/ (the documents the demo cites). Staged by this script, git-ignored: the API, worker, ML and
optimisation code trees, migrations, published experiment metrics and the study registry, keeping the repository's layout
so the code's REPO_ROOT-relative paths resolve unchanged.

Vercel runs this script as the service's buildCommand on every Git push, so pushes deploy (audit P3-OPS-02). It uses the
standard library only. What the hosted API leaves out, by design: PyTorch and LightGBM (no trained model artifacts are
deployed; forecasts use the labelled seasonal-naive baseline), local embeddings (retrieval runs lexical-only and says
so), raw datasets and model weights.

  python3 scripts/vercel/build_api.py                 stage the code (Vercel build, or before `vercel deploy`)
  python3 scripts/vercel/build_api.py --pin           rewrite deploy/vercel-api/pyproject.toml from uv.lock
  python3 scripts/vercel/build_api.py --check         fail if the committed pins differ from uv.lock (CI)
  python3 scripts/vercel/build_api.py --storage DIR   refresh the committed hosted_storage/ from a bootstrap's storage
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "deploy" / "vercel-api"
# Direct dependencies of the hosted API (a subset of the project's; no torch, lightgbm or openpyxl).
DEPS = ["fastapi", "uvicorn", "pydantic", "pydantic-settings", "sqlalchemy", "psycopg", "pgvector", "pandas", "numpy",
        "ortools", "langgraph", "httpx", "python-multipart", "itsdangerous", "pyjwt", "opentelemetry-sdk",
        "opentelemetry-exporter-otlp-proto-http", "opentelemetry-instrumentation-fastapi",
        "opentelemetry-instrumentation-httpx", "alembic"]
EXTRAS = {"psycopg": "[binary]", "pyjwt": "[crypto]", "uvicorn": "[standard]"}
TREES = ["services/api/src/supplylens", "services/api/migrations", "services/worker/src/supplylens_worker",
         "ml/supplylens_ml", "optimisation/supplylens_opt"]
STAGED = ["services", "ml", "optimisation", "artifacts", "evaluations"]    # top-level staged paths inside OUT
COMMITTED = {"index.py", "pyproject.toml", ".python-version", "hosted_storage", "hosted_data"}


def locked_versions() -> dict[str, str]:
    lock = tomllib.loads((ROOT / "uv.lock").read_text())
    return {p["name"]: p["version"] for p in lock["package"] if "version" in p}


def pyproject() -> str:
    """The hosted service's pyproject, every direct dependency pinned to the exact version in uv.lock."""
    versions = locked_versions()
    missing = [d for d in DEPS if d not in versions]
    if missing:
        raise SystemExit(f"not in uv.lock: {missing}")
    deps = "\n".join(f'  "{d}{EXTRAS.get(d, "")}=={versions[d]}",' for d in DEPS)
    return f'''# Generated by scripts/vercel/build_api.py --pin from uv.lock; CI fails if it drifts (--check).
[project]
name = "supplylens-api"
version = "0.1.0"
requires-python = ">=3.12,<3.13"
dependencies = [
{deps}
]

[tool.vercel]
entrypoint = "index:app"
'''


def stage() -> None:
    for name in STAGED:
        target = OUT / name
        if target.is_dir():
            shutil.rmtree(target)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "tests", "*.npz", "*.pt")
    for t in TREES:
        shutil.copytree(ROOT / t, OUT / t, ignore=ignore)
    shutil.copy2(ROOT / "services" / "api" / "alembic.ini", OUT / "services" / "api" / "alembic.ini")
    for f in (ROOT / "artifacts").rglob("*.json"):
        if ("experiments" in f.parts and f.name in ("metrics.json", "config.json", "selection.json")
                or f.parent.name == "reports"):
            dest = OUT / f.relative_to(ROOT)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dest)
    (OUT / "evaluations").mkdir(exist_ok=True)
    shutil.copy2(ROOT / "evaluations" / "study_registry.json", OUT / "evaluations" / "study_registry.json")
    size = sum(f.stat().st_size for name in STAGED for f in (OUT / name).rglob("*") if f.is_file())
    print(f"staged {', '.join(STAGED)} into {OUT.relative_to(ROOT)} ({size / 1e6:.1f} MB)")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pin", action="store_true", help="rewrite pyproject.toml from uv.lock")
    ap.add_argument("--check", action="store_true", help="fail if pyproject.toml differs from uv.lock")
    ap.add_argument("--storage", help="refresh hosted_storage/ from this bootstrap storage directory")
    a = ap.parse_args()
    if a.check:
        current = (OUT / "pyproject.toml").read_text()
        if current != pyproject():
            sys.exit("deploy/vercel-api/pyproject.toml differs from uv.lock: run scripts/vercel/build_api.py --pin")
        if not re.search(r"^from supplylens\.api\.app import app", (OUT / "index.py").read_text(), re.M):
            sys.exit("deploy/vercel-api/index.py does not load the application")
        print("hosted API pins match uv.lock")
        return
    if a.pin:
        (OUT / "pyproject.toml").write_text(pyproject())
        print("pinned deploy/vercel-api/pyproject.toml from uv.lock")
        return
    if a.storage:
        shutil.rmtree(OUT / "hosted_storage", ignore_errors=True)
        shutil.copytree(a.storage, OUT / "hosted_storage", ignore=shutil.ignore_patterns("exports", "*.tmp"))
    stage()


if __name__ == "__main__":
    main()
