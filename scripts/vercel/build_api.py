"""Assemble the SupplyLens API as a Vercel Python function (build/vercel-api), keeping the repository's layout so the
code's REPO_ROOT-relative paths (published study results, study registry) resolve unchanged.

What the hosted API includes: the API, worker logic (run inline: settings.inline_jobs), forecasting baseline, planner,
retrieval, published experiment metrics and the documents the demo cites. What it leaves out, by design: PyTorch and
LightGBM (no trained model artifacts are deployed; forecasts use the labelled seasonal-naive baseline), local embeddings
(retrieval runs lexical-only and says so), raw datasets and model weights.

uv run python scripts/vercel/build_api.py --storage <dir written by the hosted bootstrap>
"""
from __future__ import annotations

import argparse
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "build" / "vercel-api"
DEPS = ["fastapi", "uvicorn", "pydantic>=2", "pydantic-settings", "sqlalchemy>=2", "psycopg[binary]>=3.2", "pgvector",
        "pandas", "numpy", "ortools", "langgraph", "httpx", "python-multipart", "itsdangerous", "pyjwt[crypto]>=2.9",
        "opentelemetry-sdk", "opentelemetry-exporter-otlp-proto-http", "opentelemetry-instrumentation-fastapi",
        "opentelemetry-instrumentation-httpx"]
TREES = ["services/api/src/supplylens", "services/worker/src/supplylens_worker", "ml/supplylens_ml",
         "optimisation/supplylens_opt"]
ENTRY = '''"""Vercel entrypoint for the SupplyLens API (generated by scripts/vercel/build_api.py)."""
import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
for p in ("services/api/src", "services/worker/src", "ml", "optimisation"):
    sys.path.insert(0, str(HERE / p))
# Document bytes ship read-only with the function; the app's storage directory must be writable, so copy once per instance.
STORAGE = Path("/tmp/supplylens-storage")
if not STORAGE.exists() and (HERE / "hosted_storage").exists():
    shutil.copytree(HERE / "hosted_storage", STORAGE)
os.environ.setdefault("SUPPLYLENS_STORAGE_DIR", str(STORAGE))
os.environ.setdefault("SUPPLYLENS_INLINE_JOBS", "true")
os.environ.setdefault("SUPPLYLENS_DB_POOL_SIZE", "2")

from supplylens.api.app import app  # noqa: E402,F401
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--storage", required=True, help="storage dir written by the bootstrap that loaded the hosted database")
    a = ap.parse_args()
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "tests", "*.npz", "*.pt")
    for t in TREES:
        shutil.copytree(ROOT / t, OUT / t, ignore=ignore)
    for f in (ROOT / "artifacts").rglob("*"):
        if f.is_file() and f.suffix == ".json" and ("experiments" in f.parts and f.name in
                ("metrics.json", "config.json", "selection.json") or f.parent.name == "reports"):
            dest = OUT / f.relative_to(ROOT)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dest)
    (OUT / "evaluations").mkdir()
    shutil.copy2(ROOT / "evaluations" / "study_registry.json", OUT / "evaluations" / "study_registry.json")
    shutil.copytree(a.storage, OUT / "hosted_storage", ignore=shutil.ignore_patterns("exports", "*.tmp"))
    (OUT / "index.py").write_text(ENTRY)
    (OUT / ".python-version").write_text("3.12\n")
    deps = "\n".join(f'  "{d}",' for d in DEPS)
    (OUT / "pyproject.toml").write_text(f'''[project]
name = "supplylens-api"
version = "0.1.0"
requires-python = ">=3.12,<3.13"
dependencies = [
{deps}
]

[tool.vercel]
entrypoint = "index:app"
''')
    (OUT / "vercel.json").write_text('{\n  "$schema": "https://openapi.vercel.sh/vercel.json",\n'
                                     '  "functions": { "index.py": { "maxDuration": 60 } }\n}\n')
    size = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file())
    print(f"built {OUT.relative_to(ROOT)} ({size / 1e6:.1f} MB of source and data, dependencies installed by Vercel)")


if __name__ == "__main__":
    main()
